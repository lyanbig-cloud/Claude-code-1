"""Split the clean plate into a background and a box cut-out so the box can lift.

* GrabCut, seeded with the box silhouette, finds the exact box outline.
* fondo.jpg: the clean plate where the strip of floor the box uncovers when
  it rises (up to MAX_LIFT photo px) is rebuilt with nearby floor texture.
* caja.png: the box alone, full resolution, with an anti-aliased alpha.
* caja.json: where caja.png sits in the 2160x3840 frame, plus the box's
  bottom footprint for the shadow layer.

The box pixels themselves are copied untouched from placa.jpg.

Usage: python build_layers.py <clean_src.png> <public_dir>
"""
import json, os, sys
import cv2
import numpy as np

SRC, PUB = sys.argv[1], sys.argv[2]
MAX_LIFT = 40  # photo px; the animation never lifts higher than this
im = cv2.imread(SRC)
H, W = im.shape[:2]
plate = cv2.imread(os.path.join(PUB, "placa.jpg"))
FH, FW = plate.shape[:2]
sx, sy = FW / W, FH / H

# ---- Box matte ----------------------------------------------------------
poly = np.array([[93, 603], [523, 546], [808, 627], [808, 1060], [330, 1163], [93, 1008]], np.int32)
P = np.zeros((H, W), np.uint8)
cv2.fillPoly(P, [poly], 1)
m = np.full((H, W), cv2.GC_BGD, np.uint8)
m[cv2.dilate(P, np.ones((25, 25))) > 0] = cv2.GC_PR_BGD
m[P > 0] = cv2.GC_PR_FGD
m[cv2.erode(P, np.ones((21, 21))) > 0] = cv2.GC_FGD
cv2.grabCut(im, m, None, np.zeros((1, 65)), np.zeros((1, 65)), 6, cv2.GC_INIT_WITH_MASK)
fg = ((m == cv2.GC_FGD) | (m == cv2.GC_PR_FGD)).astype(np.uint8)
n, lab, st, _ = cv2.connectedComponentsWithStats(fg)
fg = (lab == 1 + np.argmax(st[1:, 4])).astype(np.uint8)
fg = cv2.morphologyEx(fg, cv2.MORPH_CLOSE, np.ones((5, 5)))
# GrabCut also takes the dark contact shadow under the bottom edges. Keep only
# a thin rim of it (the cardboard's own edge); the rest belongs to the floor.
# Edge lines measured where the dark line starts: (150,1031)-(250,1103) on the
# left face and (400,1147)-(560,1108) on the front face.
RIM = 4
yy, xx = np.mgrid[0:H, 0:W]
left_edge = 1031 + (xx - 150) * (1103 - 1031) / 100 + RIM
front_edge = 1147 + (xx - 400) * (1108 - 1147) / 160 + RIM
fg = (fg & ((xx > 330) | (yy <= left_edge)) & ((xx <= 330) | (yy <= front_edge))).astype(np.uint8)

# Full-resolution alpha: upscale the binary matte smoothly, then a hair of blur.
alpha = cv2.resize(fg.astype(np.float32), (FW, FH), interpolation=cv2.INTER_LINEAR)
alpha = cv2.GaussianBlur(alpha, (0, 0), 0.9)
alpha = np.clip((alpha - 0.5) * 1.6 + 0.5, 0, 1)

ys, xs = np.nonzero(alpha > 0.01)
x0, y0, x1, y1 = xs.min() - 4, ys.min() - 4, xs.max() + 5, ys.max() + 5
rgba = np.dstack([plate[y0:y1, x0:x1], (alpha[y0:y1, x0:x1] * 255).astype(np.uint8)])
cv2.imwrite(os.path.join(PUB, "caja.png"), rgba)

# ---- Background: rebuild the strip the box uncovers ------------------------
lifted = np.roll(fg, -MAX_LIFT, axis=0)
# Include the dark contact line just under the box: once it floats, that
# hard line must not stay on the floor.
reveal = ((cv2.dilate(fg, np.ones((13, 13))) > 0) & (lifted == 0)).astype(np.uint8)
# Rebuild the strip from the floor only (the box counts as unknown so its
# colours never leak in), add matching grain, and feather it widely into the
# floor so there is no edge. Under a floating box this reads as the floor in
# its own soft shadow, which the Remotion shadow layer then deepens.
src = im.astype(np.float32)
unknown = (cv2.dilate(((reveal > 0) | (fg > 0)).astype(np.uint8), np.ones((5, 5))) * 255)
filled = cv2.inpaint(im, unknown, 15, cv2.INPAINT_TELEA).astype(np.float32)
rng = np.random.default_rng(5)
filled += rng.standard_normal(filled.shape[:2]).astype(np.float32)[..., None] * 5
soft = np.clip(cv2.GaussianBlur(cv2.dilate(reveal, np.ones((9, 9))).astype(np.float32), (0, 0), 6) * 1.6, 0, 1)
soft = np.maximum(soft, reveal.astype(np.float32))[..., None]
soft = soft * (1 - fg[..., None])  # never touch what the box covers at rest
clean_bg = np.clip(src * (1 - soft) + filled * soft, 0, 255)
reveal = (soft[..., 0] > 0.01).astype(np.uint8)

# Same upscale as the plate, then paste only the rebuilt strip into it.
big = cv2.resize(clean_bg.astype(np.uint8), (FW, int(round(H * FW / W))), interpolation=cv2.INTER_LANCZOS4)
big = cv2.addWeighted(big, 1.35, cv2.GaussianBlur(big, (0, 0), 1.6), -0.35, 0)
big = cv2.resize(big, (FW, FH), interpolation=cv2.INTER_AREA)
rm = cv2.resize(cv2.dilate(reveal, np.ones((5, 5))).astype(np.float32), (FW, FH), interpolation=cv2.INTER_LINEAR)
rm = cv2.GaussianBlur(rm, (0, 0), 2)[..., None]
fondo = plate.astype(np.float32) * (1 - rm) + big.astype(np.float32) * rm
cv2.imwrite(os.path.join(PUB, "fondo.jpg"), fondo.astype(np.uint8), [cv2.IMWRITE_JPEG_QUALITY, 94])

json.dump(
    {
        "_doc": "Generated by scripts/build_layers.py. Pixel positions in the 2160x3840 frame; footprint in photo px.",
        "x": int(x0),
        "y": int(y0),
        "width": int(x1 - x0),
        "height": int(y1 - y0),
        "maxLift": MAX_LIFT,
        # Bottom face of the box (left, front and right corners; the back one inferred).
        "footprint": [[93, 1008], [330, 1163], [808, 1060], [571, 905]],
    },
    open(os.path.join(PUB, "caja.json"), "w"),
    indent=1,
)
print("box", x0, y0, x1 - x0, y1 - y0)
