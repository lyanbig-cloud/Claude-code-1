"""Route the Tampa -> Miami truck leg over the Natural Earth 10m road network.

Builds a graph from every ne_10m_roads segment inside Florida, snaps the two
ports (Natural Earth 10m ports) to their nearest road vertices and takes the
shortest path over interstates and expressways only (I-75 "Alligator
Alley" across the Everglades). Writes the polyline as [lon, lat] pairs.

Usage: python build_road.py <data_dir> <florida.json> <out_json>
"""
import json, math, os, sys
import networkx as nx
from shapely.geometry import shape, box, LineString

DATA, GEO, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
geo = json.load(open(GEO))
start = tuple(geo["places"]["tampa"]["coord"])
end = tuple(geo["places"]["miami"]["coord"])
clip = box(-83.5, 24.8, -79.8, 28.6)


def dist(a, b):
    k = math.cos(math.radians((a[1] + b[1]) / 2))
    return math.hypot((a[0] - b[0]) * k, a[1] - b[1]) * 111.2  # km


G = nx.Graph()
for f in json.load(open(os.path.join(DATA, "ne_10m_roads.geojson")))["features"]:
    g = shape(f["geometry"])
    if not g.intersects(clip):
        continue
    # Interstates and expressways only: the network a container truck uses.
    if f["properties"].get("type") not in ("Major Highway", "Beltway"):
        continue
    cost = 1.0
    for line in getattr(g, "geoms", [g]):
        pts = [(round(x, 5), round(y, 5)) for x, y in line.coords]
        for a, b in zip(pts, pts[1:]):
            G.add_edge(a, b, w=dist(a, b) * cost)

# Join vertices that nearly coincide (separately digitised segments).
nodes = list(G.nodes)
grid = {}
for n in nodes:
    grid.setdefault((round(n[0], 2), round(n[1], 2)), []).append(n)
for cell, ns in grid.items():
    near = [m for dx in (-0.01, 0, 0.01) for dy in (-0.01, 0, 0.01)
            for m in grid.get((round(cell[0] + dx, 2), round(cell[1] + dy, 2)), [])]
    for a in ns:
        for b in near:
            if a != b and dist(a, b) < 3.0 and not G.has_edge(a, b):
                G.add_edge(a, b, w=dist(a, b) * 1.2)

# Snap both ports inside the largest connected part of the network.
main = max(nx.connected_components(G), key=len)
s = min(main, key=lambda n: dist(n, start))
e = min(main, key=lambda n: dist(n, end))
# Via I-75 at Naples: the classic truck corridor (I-275 / I-75 / Alligator
# Alley), rather than the inland Turnpike alternative.
VIA = (-81.76, 26.16)
v = min(main, key=lambda n: dist(n, VIA))
path = nx.shortest_path(G, s, v, weight="w") + nx.shortest_path(G, v, e, weight="w")[1:]
length = sum(dist(a, b) for a, b in zip(path, path[1:]))  # real km
simple = LineString(path).simplify(0.002)
coords = [[round(x, 5), round(y, 5)] for x, y in simple.coords]
json.dump(
    {
        "_doc": "Tampa -> Miami over Natural Earth 10m roads (shortest path). Generated by scripts/build_road.py.",
        "lengthKm": round(length, 1),
        "snapKm": [round(dist(s, start), 2), round(dist(e, end), 2)],
        "points": coords,
    },
    open(OUT, "w"),
)
print(f"{len(coords)} points, {length:.0f} km, snap {dist(s, start):.1f} / {dist(e, end):.1f} km")
